"""Tests for the DomU local MQTT broker (the msg vchan channel).

The DomU msg channel is a local mosquitto broker: the domain applications
connect to the broker's UNIX socket and a single upstream bridge carries
the domain's traffic over the vchan (issue #258). The vchan hop itself
requires Xen and is validated on hardware (run 13); these tests validate
the local broker half of the architecture:

- every local client is multiplexed by the broker: two or more clients
  publish concurrently on the same socket (the previous architecture
  allowed only one client per vchan connection),
- the bridge configuration generated by ``setup-vchan.sh`` is accepted by
  a real mosquitto broker (mosquitto 2.x bridge syntax: the ``connection``
  block, ``remote_clientid``, ``address host:port``, wildcard ``topic``,
  ``notifications``).
"""

import os
import subprocess
import threading
import time

from safecor_emulator import MosquittoBroker
from safecor_emulator.broker import _find_free_port

from safecor import ConnectionType, MqttClient


def test_local_broker_multiplexes_clients(tmp_path):
    """Two or more clients on the same broker socket publish concurrently."""
    sock = str(tmp_path / "mqtt.sock")
    broker = MosquittoBroker(port=_find_free_port(), unix_socket=sock)
    broker.start()
    try:
        got_a, got_b = {}, {}
        ev_a, ev_b = threading.Event(), threading.Event()

        client_a = MqttClient("test-client-a", ConnectionType.UNIX_SOCKET, sock)
        client_b = MqttClient("test-client-b", ConnectionType.UNIX_SOCKET, sock)
        # One topic per receiver: a client must not see its own messages.
        client_a.on_connected = lambda: client_a.subscribe("test/for-a")
        client_b.on_connected = lambda: client_b.subscribe("test/for-b")
        client_a.on_message = lambda topic, payload: (got_a.update(payload), ev_a.set())
        client_b.on_message = lambda topic, payload: (got_b.update(payload), ev_b.set())
        client_a.start()
        client_b.start()

        deadline = time.time() + 10
        while time.time() < deadline and not (
            client_a.connected and client_b.connected
        ):
            time.sleep(0.1)
        assert client_a.connected, "client A did not connect to the local broker"
        assert client_b.connected, "client B did not connect to the local broker"

        # Client A publishes, client B receives (and vice versa) while both
        # clients stay connected: this is exactly the scenario that the
        # single-vchan-connection architecture could not handle.
        client_a.publish("test/for-b", {"from": "a"})
        assert ev_b.wait(10), "client B did not receive the message of client A"
        assert got_b.get("from") == "a"

        client_b.publish("test/for-a", {"from": "b"})
        assert ev_a.wait(10), "client A did not receive the message of client B"
        assert got_a.get("from") == "b"

        client_a.stop()
        client_b.stop()
    finally:
        broker.stop()


def test_broker_with_upstream_bridge_config(tmp_path):
    """The DomU broker configuration (UNIX listener + upstream bridge) starts.

    The configuration mirrors what ``setup-vchan.sh`` generates in a DomU.
    The bridge endpoint (a free port on 127.0.0.1) is unreachable in this
    environment: the broker must start anyway and serve the local clients
    while the bridge retries in the background.
    """
    sock = str(tmp_path / "mqtt.sock")
    workdir = tmp_path / "mosq"
    workdir.mkdir()
    conf = workdir / "mosquitto.conf"
    conf.write_text(
        "log_dest none\n"
        "allow_anonymous true\n"
        f"listener 0 {sock}\n"
        "connection safecor-test-domain-bridge\n"
        "remote_clientid safecor-test-domain-bridge\n"
        f"address 127.0.0.1:{_find_free_port()}\n"
        "topic # both 0\n"
        "notifications false\n"
    )
    log = workdir / "mosquitto.log"
    with open(log, "ab") as lf:
        proc = subprocess.Popen(
            ["mosquitto", "-c", str(conf)],
            stdout=lf,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
        )
    try:
        deadline = time.time() + 10
        while time.time() < deadline and not os.path.exists(sock):
            assert proc.poll() is None, (
                f"mosquitto exited early (code={proc.returncode}): {log.read_text()}"
            )
            time.sleep(0.1)
        assert os.path.exists(sock), "the broker UNIX socket was not created"

        client = MqttClient("bridge-conf-test", ConnectionType.UNIX_SOCKET, sock)
        client.start()
        deadline = time.time() + 10
        while time.time() < deadline and not client.connected:
            time.sleep(0.1)
        assert client.connected, "client did not connect to the bridged broker"
        client.stop()
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
